export function fmtNum(lang, n, dp = 0) {
  return new Intl.NumberFormat(lang === 'bn' ? 'bn-BD' : 'en-US',
    { maximumFractionDigits: dp, minimumFractionDigits: dp, useGrouping: false }).format(n);
}

/** t('bn', 'r.hiSome', {n: 29, when: 'night'}): numbers get native digits, strings pass through. */
export function t(lang, key, vars = {}) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, typeof v === 'number' ? fmtNum(lang, v, Number.isInteger(v) ? 0 : 1) : String(v));
  }
  return s;
}
